def _resolve_column_index(header: List[str], wanted: str) -> int:
    wanted_norm = wanted.strip().lower()
    for i, name in enumerate(header):
        if name is not None and name.strip().lower() == wanted_norm:
            return i
    available = ", ".join(str(f) for f in header)
    raise ValueError(f"В CSV не найдена колонка '{wanted}'. Доступные колонки: {available}")


def load_headings_from_csv(
    file_path: str,
    text_column: str = "headline",
    label_column: str = "category",
    delimiter: str = ",",
) -> Tuple[List[str], List[str]]:
    headings = []
    categories = []
    repaired = 0
    skipped = 0

    with open(file_path, "r", encoding="utf-8-sig", newline="") as file:
        reader = csv.reader(file, delimiter=delimiter)
        try:
            header = next(reader)
        except StopIteration:
            raise ValueError("CSV-файл пустой или не содержит строку с названиями колонок.")

        text_idx = _resolve_column_index(header, text_column)
        label_idx = _resolve_column_index(header, label_column)
        ncols = len(header)

        for row in reader:
            if not row or all((cell or "").strip() == "" for cell in row):
                continue

            if len(row) == ncols:
                text = row[text_idx]
                label = row[label_idx]
            elif len(row) > ncols and text_idx == 0 and label_idx == ncols - 1:
                label = row[-1]
                text = delimiter.join(row[:-1])
                repaired += 1
            else:
                skipped += 1
                continue

            text = text.strip()
            label = label.strip()
            if text and label:
                headings.append(text)
                categories.append(label)

    if len(headings) == 0:
        raise ValueError("После чтения CSV не найдено ни одной размеченной строки.")
    if repaired or skipped:
        print(f"  [CSV] восстановлено строк с запятой в заголовке: {repaired}; пропущено: {skipped}")
    return headings, categories


def clean_text(raw_string: str) -> str:
    clean_string = raw_string.lower()
    clean_string = re.sub(r"[^а-яёa-z0-9\s-]", " ", clean_string)
    clean_string = re.sub(r"\s+", " ", clean_string).strip()
    return clean_string


def tokenize(clean_string: str) -> List[str]:
    return clean_string.split()


